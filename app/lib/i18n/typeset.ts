/**
 * Типографіка рядка перед показом: де рядку НЕ можна ламатись. Браузер
 * переносить по будь-якому пробілу, тож без цього «з», «на», «і» висять у
 * кінці рядка, а тире починає новий. Нерозривний пробіл (U+00A0) не міняє
 * вигляду — лише забирає браузеру право ламати саме тут.
 *
 * Правила (українська верстка):
 * - одно- і дволітерне слово (прийменник, сполучник, частка) тримається з
 *   наступним: «у шести», «на руках», «і на якій»;
 * - тире не починає рядок: тримається з попереднім словом;
 * - число не відривається від слова чи одиниці за ним: «30 днів», «000 zł».
 *
 * Перенос `\n` (абзаци в словнику) не чіпається.
 */
const NBSP = '\u00A0';

export function typeset(text: string): string {
  return text
    .replace(/(?<=^|[\s\u00A0(«"„])(\p{L}{1,2}) (?=\S)/gu, `$1${NBSP}`)
    .replace(/ (—|–) /g, `${NBSP}$1 `)
    .replace(/(\d) (?=\p{L})/gu, `$1${NBSP}`);
}

/** Увесь словник одразу: ключі ті самі, значення — після `typeset`. */
export function typesetDictionary(dictionary: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(dictionary).map(([key, text]) => [key, typeset(text)]));
}
