import type { Answers } from '@/lib/calc/types';

/**
 * Сторінка-відповідь `/{мова}/poland/<slug>`: один файл змісту на сторінку й
 * мову, без розмітки. Текст живе тут, а не в `.tsx` — кирилиця в компонентах
 * заборонена тестом, а шаблон один на всі сторінки.
 *
 * **Цифр у тексті немає.** Число вставляється плейсхолдером
 * `{{формат:rule_id/шлях}}` і бере значення й джерело з правила через `calc/`
 * (`answer-page.ts`); guard-тест падає на будь-якій цифрі поза плейсхолдером.
 * Формати: `amount` — сума як у джерелі («8 517 200», «498,35»), `percent` —
 * частка як відсоток («12%»). Одиницю («zł», «грн») пише текст.
 *
 * Твердження без числа теж цитує джерело: `{{cite:rule_id}}` у кінці речення
 * нічого не друкує, а додає правило в блок джерел.
 */
export interface AnswerPageContent {
  /** Сегмент адреси латиницею: `ryczalt-it` → `/uk/poland/ryczalt-it`. */
  slug: string;
  /** `<h1>` і заголовок вкладки та пошуку. */
  title: string;
  /** Опис для пошуку й прев'ю лінка, одне-два речення. */
  description: string;
  lead: string;
  body: Block[];
  /**
   * Відповіді, які випливають із теми сторінки (сторінка для програміста →
   * `workKind: 'programming'`). Кнопка відкриває анкету з ними; решту людина
   * відповідає сама. Лише те, що тема каже напевно, — не здогадки про читача.
   */
  prefill: Partial<Answers>;
  /** Гайд теми 4.1; місце під нього на сторінці приховане, доки гайдів немає. */
  guide?: string;
}

export type Block = { kind: 'h2'; text: string } | { kind: 'p'; text: string } | { kind: 'list'; items: string[] };
