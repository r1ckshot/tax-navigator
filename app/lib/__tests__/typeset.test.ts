import { describe, expect, it } from 'vitest';
import { typeset, typesetDictionary } from '../i18n/typeset';
import { uk } from '../i18n/uk';

/** Нерозривний пробіл у еталонах — видимим `~`, щоб тест читався. */
const show = (s: string) => s.replace(/ /g, '~');

describe('typeset: де рядку не можна ламатись', () => {
  it('коротке слово тримається з наступним, і кілька поспіль теж', () => {
    expect(show(typeset('у шести варіантах'))).toBe('у~шести варіантах');
    expect(show(typeset('руках і на якій підставі'))).toBe('руках і~на~якій підставі');
  });

  it('тире не починає рядок', () => {
    expect(show(typeset('на руках — і на якій'))).toBe('на~руках~— і~на~якій');
  });

  it('дефіс усередині слова не дає переносу, а тире між пробілами не чіпає', () => {
    expect(typeset('лишається по-різному')).toBe('лишається по\u2060-\u2060різному');
    expect(typeset('IT-B2B')).toBe('IT\u2060-\u2060B2B');
    expect(typeset('-5 zł')).toBe('-5\u00A0zł');
  });

  it('число не відривається від слова за ним', () => {
    expect(show(typeset('більш ніж на 30 днів'))).toBe('більш ніж на~30~днів');
  });

  it('довгі слова й перенос абзацу не чіпає', () => {
    expect(show(typeset('Дохід той самий\nвін не є'))).toBe('Дохід той самий\nвін не~є');
  });

  it('повторний прохід нічого не змінює (словник + підстановка змінних)', () => {
    const once = typeset('і на 30 днів — у шести');
    expect(typeset(once)).toBe(once);
  });

  it('словник показу вже пройшов типографіку', () => {
    // «Що» і «на» — дволітерні: тримаються з наступним словом.
    expect(show(uk['brand.headline'])).toBe('Що~лишиться на~руках після податків?');
    expect(typesetDictionary({ a: 'з джерелом' })).toEqual({ a: 'з джерелом' });
  });
});
