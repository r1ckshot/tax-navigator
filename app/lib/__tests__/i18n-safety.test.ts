import { describe, expect, it } from 'vitest';
import { uk } from '../i18n/uk';

/**
 * Анти-регрес на пораду в тексті UI (product-safety.md): продукт порівнює
 * варіанти, але не ранжує їх і не каже, що обрати. Кожен патерн нижче колись
 * був або міг би бути в `uk.ts`; «рекомендація» у запереченні («не рекомендація»)
 * свідомо не ловиться, бо це саме дисклеймер.
 */
const RANKING = [
  /краще/i,
  /вигідніш/i,
  /найвигідн/i,
  /найкращ/i,
  /найпередбачуван/i,
  /найнадійн/i,
  /рекоменду(ємо|ю)/i,
  /радимо/i,
  /(оберіть|обирайте|виберіть)/i,
  /(варто|слід|треба) (обрати|вибрати|відкрити|перейти|закрити)/i,
  // `\b` у JS знає лише латиницю, тож межу слова для кирилиці задає `\p{L}`.
  /(?<!\p{L})тобі(?!\p{L})/iu,
];

describe('тексти UI не радять і не ранжують варіанти', () => {
  it.each(RANKING.map((re) => [re.source, re] as const))('жоден рядок не містить /%s/', (_src, re) => {
    const hits = Object.entries(uk).filter(([, text]) => re.test(text));
    expect(hits).toEqual([]);
  });

  // Відповіді анкети читає будь-хто, тож форма не має вгадувати рід.
  it('варіанти відповідей без чоловічого роду в минулому часі', () => {
    const gendered = Object.entries(uk).filter(
      ([key, text]) => key.startsWith('q.') && /(?<!\p{L})(впевнений|\p{L}{3,}ав)(?!\p{L})/iu.test(text),
    );
    expect(gendered).toEqual([]);
  });
});
