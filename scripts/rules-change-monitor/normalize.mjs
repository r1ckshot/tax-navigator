// Нормалізація польських чисел зі сторінок держсайтів (zus.pl, podatki.gov.pl)
// у звичайний JS `number`. Джерела форматують тисячі нерозривним пробілом і
// десяткові — комою (`4 806,00 zł`), тож без цього кроку `diff.mjs` порівнював
// би рядки, а не числа.

/**
 * Перетворює сире значення з джерела або з матриці на число.
 *
 * Свідомо НЕ вгадує неоднозначні формати: рядок із двома різними
 * роздільниками (`"1,234,567"`) — це не польський запис (польська кома завжди
 * десяткова, роздільник тисяч — пробіл, не кома), тож мовчазна здогадка тут
 * коштувала б неправильної ставки людині, яка на це число покладається.
 *
 * @param {unknown} raw
 * @returns {number|null}
 */
export function normalizeNumber(raw) {
  if (typeof raw === "number") {
    return Number.isFinite(raw) ? raw : null;
  }
  if (typeof raw !== "string") {
    return null;
  }

  const trimmed = raw.trim();
  if (trimmed === "" || !/\d/.test(trimmed)) {
    return null;
  }

  // Прибрати все, що не цифра/кома/крапка/мінус/відсоток одним проходом:
  // валюту (zł, PLN), звичайний пробіл і обидва нерозривні (U+00A0, U+202F) —
  // усі три трапляються як роздільник тисяч залежно від того, який рушій
  // зверстав сторінку, і жоден з них не несе смислу для самого числа.
  let s = trimmed.replace(/[^0-9,.\-%]/g, "");
  // Відсоток: знак лише позначає одиницю, на саме число не впливає.
  s = s.replace(/%/g, "");

  if (s === "" || !/\d/.test(s)) {
    return null;
  }

  const hasComma = s.includes(",");
  const hasDot = s.includes(".");

  if (hasComma && hasDot) {
    // Обидва символи в одному рядку одночасно — польський запис так не
    // пише (крапка як роздільник тисяч у джерелах не трапляється), і
    // вгадувати, який із двох — десятковий, а який — сміття, не будемо.
    return null;
  }

  if (hasComma) {
    // Кома завжди одна в польському десятковому записі: більше однієї —
    // ознака чужого/пошкодженого формату, не польських тисяч.
    const parts = s.split(",");
    if (parts.length !== 2) {
      return null;
    }
    s = `${parts[0]}.${parts[1]}`;
  } else if (hasDot) {
    const parts = s.split(".");
    if (parts.length > 2) {
      // "1.234.567" — крапка як роздільник тисяч; польський запис так не
      // пише (там для тисяч пробіл), тож це чужий формат — не вгадуємо.
      return null;
    }
  }

  if (!/^-?\d+(\.\d+)?$/.test(s)) {
    return null;
  }

  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}

/**
 * Чи два сирі значення позначають те саме число після нормалізації.
 * Допуск < 0.005 покриває копійки/грошики, які округлення форматування
 * інколи губить чи додає.
 *
 * @param {unknown} a
 * @param {unknown} b
 * @returns {boolean}
 */
export function sameAfterNormalize(a, b) {
  const na = normalizeNumber(a);
  const nb = normalizeNumber(b);
  if (na === null || nb === null) {
    return false;
  }
  return Math.abs(na - nb) < 0.005;
}
