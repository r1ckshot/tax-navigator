// Дешева перевірка чужої сторінки ДО того, як щось із неї доїде до моделі.
//
// Межа, заради якої цей модуль існує: `cycle.mjs` САМ іде на zus.pl і
// podatki.gov.pl, тягне HTML, який пише хтось інший, і кладе витягнуте в звіт.
// Звіт читає `drift-reviewer` — тобто чужий текст зустрічає агента, що має
// доступ до репо. Сторінка тут не наказ, а дані, написані невідомою людиною.
//
// Чому перевірка стоїть саме тут, а не в промпті рецензента: промпт — прохання,
// а це кілька рядків звичайного коду в самому конвеєрі. Вони коштують нуль
// токенів, спрацьовують до запуску моделі й видно їх прямо в діфі.
//
// Червоний вхід НЕ лікується. Ми не вирізаємо знайдену інструкцію, щоб пустити
// решту сторінки далі: сторінка, яка одного разу несла наказ, більше не є
// джерелом цифри — вона позначається непридатною, і цифру підтверджує людина.
// Тиха «санітизація» дала б звіт, що виглядає перевіреним, а таким не є, —
// рівно та помилка, проти якої стоїть уся нарізка (`states.mjs`).

/**
 * Стеля вхідного тексту. Жива сторінка складок ZUS — 994 КБ (заміряно
 * 2026-08-26), тож 1,5 МБ лишає запас і при цьому обмежує роботу регулярок і
 * розмір того, що взагалі може дійти до звіту.
 *
 * Обрізаємо, а не блокуємо: обрізання може відсікти маркер, і тоді екстрактор
 * поверне null, а запис стане `unavailable` з названою причиною. Це чесне «не
 * перевірили», а не хибний `match`.
 */
export const MAX_INPUT_CHARS = 1_500_000;

/**
 * Блоки, що ніколи не мають брати участі ні в перевірці, ні у витягу числа.
 * Ріжемо їх ПЕРШИМИ і не скануємо: на державних сторінках лежить чужа
 * аналітика зі словами на кшталт `apiKey`, і сканування скриптів дало б
 * хибнопозитив на кожному другому циклі. Вміст, який видалено до всього
 * іншого, до моделі не доїде в принципі, тож і шукати в ньому нема чого.
 */
const INERT_BLOCKS = [
  /<script\b[^>]*>[\s\S]*?<\/script\s*>/gi,
  /<style\b[^>]*>[\s\S]*?<\/style\s*>/gi,
  /<noscript\b[^>]*>[\s\S]*?<\/noscript\s*>/gi,
];

/** HTML-коментарі: класичний носій прихованого тексту. Скануються, тоді ріжуться. */
const HTML_COMMENT = /<!--[\s\S]*?-->/g;

/**
 * Ознаки того, що в тексті сторінки лежить звернення до агента, а не проза для
 * людини.
 *
 * Патерни описують ЗМІСТ наказу, а не спосіб його сховати. Сховати текст можна
 * сотнею способів (`display:none`, нульовий кегль, білим по білому, коментар,
 * атрибут `title`), і гонитва за кожним програшна: вони всі однаково нормальні
 * на живій верстці, тож ловились би хибнопозитивами. Незмінне інше — наказ
 * мусить НАЗВАТИ предмет: файл секретів, теку конфігурації агента, матрицю
 * правил, спосіб відправити щось назовні. Тому скануємо весь текст сторінки
 * разом із коментарями й атрибутами, і дивимось на предмет.
 *
 * Кожен запис несе `label` — людську назву без жодного символу зі сторінки.
 * Дослівний фрагмент у звіт не потрапляє свідомо: звіт читає модель, і
 * процитований наказ доїхав би до неї всередині повідомлення про блокування,
 * тобто перевірка сама стала б каналом доставки.
 */
export const INJECTION_PATTERNS = Object.freeze([
  {
    id: "secret-file",
    label: "згадка файлів із секретами",
    re: /(?:^|[\s/:"'`(])\.env\b|\bid_rsa\b|(?:^|[\s/:"'`(])\.ssh(?:[/\s"'`)]|$)/i,
  },
  {
    id: "agent-config",
    label: "згадка конфігурації агента",
    re: /(?:^|[\s/:"'`(])\.claude(?:[/\s"'`)]|$)|\bCLAUDE\.md\b|\bsettings\.json\b|\bAGENTS\.md\b/i,
  },
  {
    id: "matrix-write",
    label: "звернення до матриці правил",
    re: /\brules\.2026\.json\b|\brules-change-monitor\b/i,
  },
  {
    id: "instruction-override",
    label: "спроба перебити попередні інструкції",
    re: /\b(?:ignore|disregard|forget)\b[^.\n]{0,40}\b(?:previous|prior|above|earlier|all)\b[^.\n]{0,40}\b(?:instruction|prompt|rule)/i,
  },
  {
    id: "role-switch",
    label: "підміна ролі або системного промпту",
    re: /<\|?(?:system|assistant)\|?>|\b(?:system|developer)\s+prompt\b|\byou\s+are\s+now\s+(?:an?\s+)?(?:assistant|agent|model)\b/i,
  },
  {
    id: "credential",
    label: "згадка ключів і токенів доступу",
    re: /\b(?:api[_\s-]?key|oauth[_\s-]?token|access[_\s-]?token|ANTHROPIC_API_KEY|GITHUB_TOKEN|CLAUDE_CODE_OAUTH_TOKEN)\b/i,
  },
  {
    id: "exfiltration",
    label: "вказівка відправити щось назовні",
    re: /\b(?:curl|wget)\s+(?:-\S+\s+)*https?:\/\/|\b(?:send|post|upload|exfiltrat\w*|wyślij|prześlij|надішли|відправ\w*)\b[^.\n]{0,40}\b(?:token|secret|key|klucz|credential|ключ|секрет)\b/i,
  },
]);

/**
 * Що знайдено в тексті. Повертає ПЕРШЕ спрацювання — далі шукати нема сенсу:
 * рішення однакове, а перелік усіх збігів лише роздував би повідомлення чужим
 * матеріалом.
 *
 * @param {string} text
 * @returns {{ id: string, label: string }|null}
 */
export function detectInjection(text) {
  if (typeof text !== "string" || text === "") return null;
  for (const { id, label, re } of INJECTION_PATTERNS) {
    if (re.test(text)) return { id, label };
  }
  return null;
}

/**
 * Прохід сторінки перед усім іншим: вирізати інертні блоки → обрізати →
 * перевірити → прибрати коментарі.
 *
 * Порядок не косметичний, і саме він був спершу неправильний. Обрізання стояло
 * ПЕРШИМ (щоб регулярки платили за меншу довжину), але зріз посеред `<script>`
 * лишав у тексті хвіст чужої аналітики без закривального тега — той уже не
 * матчився, а слова на кшталт `apiKey` матчились, і звичайна сторінка дістала б
 * `blocked` разом із кодом виходу 2. Тож інертні блоки ріжуться до обрізання.
 *
 * Коментарі — ОСТАННІМИ: спершу їх треба прочитати, інакше прихована інструкція
 * просто зникла б, цикл пройшов би зелено, і ми ніколи не дізнались би, що
 * сторінку чіпали.
 *
 * @param {string|null} html
 * @returns {{ html: string|null, blocked: boolean, failure_reason: string|null, truncated: boolean }}
 */
export function screenSource(html) {
  if (typeof html !== "string") {
    return { html: null, blocked: false, failure_reason: null, truncated: false };
  }

  let text = html;
  for (const block of INERT_BLOCKS) {
    text = text.replace(block, " ");
  }

  const truncated = text.length > MAX_INPUT_CHARS;
  if (truncated) text = text.slice(0, MAX_INPUT_CHARS);

  const hit = detectInjection(text);
  if (hit) {
    return {
      html: null,
      blocked: true,
      failure_reason: `вхід заблоковано до моделі: ${hit.label} (${hit.id})`,
      truncated,
    };
  }

  return {
    html: text.replace(HTML_COMMENT, " "),
    blocked: false,
    failure_reason: null,
    truncated,
  };
}
